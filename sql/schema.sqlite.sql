CREATE TABLE IF NOT EXISTS University (
    UniversityID INTEGER PRIMARY KEY,
    Name VARCHAR(255) NOT NULL,
    Location VARCHAR(8) NOT NULL,
    City VARCHAR(255),
    Tuition DECIMAL(12,2) CHECK(Tuition >= 0),
    TuitionOutState DECIMAL(12,2) CHECK(TuitionOutState >= 0),
    Website VARCHAR(512),
    Source VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS Major (
    MajorID INTEGER PRIMARY KEY,
    MajorName VARCHAR(255) NOT NULL,
    Field VARCHAR(255),
    CIPCode VARCHAR(4) UNIQUE
);
CREATE TABLE IF NOT EXISTS Program (
    ProgramID INTEGER PRIMARY KEY AUTOINCREMENT,
    Name VARCHAR(255) NOT NULL,
    UniversityID INTEGER NOT NULL REFERENCES University(UniversityID),
    MajorID INTEGER NOT NULL REFERENCES Major(MajorID),
    DegreeType VARCHAR(255) NOT NULL,
    MedianSalary DECIMAL(12,2) CHECK(MedianSalary >= 0),
    Source VARCHAR(255) NOT NULL,
    SourceKey VARCHAR(64) UNIQUE,
    EarningsMetric VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS Job (
    JobID INTEGER PRIMARY KEY AUTOINCREMENT,
    JobTitle VARCHAR(255) NOT NULL,
    Company VARCHAR(255),
    Location VARCHAR(255),
    AvgSalary DECIMAL(12,2) CHECK(AvgSalary >= 0)
);
CREATE TABLE IF NOT EXISTS MajorJob (
    MajorID INTEGER NOT NULL REFERENCES Major(MajorID),
    JobID INTEGER NOT NULL REFERENCES Job(JobID),
    PRIMARY KEY(MajorID,JobID)
);
CREATE TABLE IF NOT EXISTS User (
    UserID INTEGER PRIMARY KEY AUTOINCREMENT,
    Username VARCHAR(100) NOT NULL UNIQUE,
    PasswordHash VARCHAR(255) NOT NULL,
    Email VARCHAR(255),
    PreferredLocation VARCHAR(255),
    PreferredMajor INTEGER REFERENCES Major(MajorID),
    PreferredJob INTEGER REFERENCES Job(JobID),
    IsAdmin INTEGER NOT NULL DEFAULT 0 CHECK(IsAdmin IN (0,1))
);
CREATE TABLE IF NOT EXISTS Bookmark (
    UserID INTEGER NOT NULL REFERENCES User(UserID) ON DELETE CASCADE,
    ProgramID INTEGER NOT NULL REFERENCES Program(ProgramID) ON DELETE CASCADE,
    PRIMARY KEY(UserID,ProgramID)
);
CREATE TABLE IF NOT EXISTS Comparison (
    ComparisonID INTEGER PRIMARY KEY AUTOINCREMENT,
    UserID INTEGER NOT NULL REFERENCES User(UserID) ON DELETE CASCADE,
    ProgramID1 INTEGER NOT NULL REFERENCES Program(ProgramID) ON DELETE CASCADE,
    ProgramID2 INTEGER NOT NULL REFERENCES Program(ProgramID) ON DELETE CASCADE,
    NoteFromUser TEXT,
    CHECK(ProgramID1 != ProgramID2)
);
CREATE TABLE IF NOT EXISTS Alert (
    AlertID INTEGER PRIMARY KEY AUTOINCREMENT,
    UserID INTEGER NOT NULL REFERENCES User(UserID) ON DELETE CASCADE,
    Message TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_program_major ON Program(MajorID);
CREATE INDEX IF NOT EXISTS idx_program_university ON Program(UniversityID);
CREATE INDEX IF NOT EXISTS idx_comparison_user ON Comparison(UserID);
CREATE INDEX IF NOT EXISTS idx_alert_user ON Alert(UserID);
